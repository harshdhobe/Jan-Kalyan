"""
prepare_frontend_data.py
------------------------
Generates lightweight JS data modules for the browser frontend:
  1. frontend/data/rules.js  -> window.TIER1_RULES
  2. frontend/data/fields.js -> window.FIELD_CATALOG
  3. frontend/data/personas.js -> window.SAMPLE_PERSONAS

This allows the UI to run seamlessly both directly from file:// and http://.
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TIER1_DIR = REPO_ROOT / "data" / "rules" / "tier1"
CATALOG_FILE = REPO_ROOT / "data" / "catalog" / "fields.json"
OUT_DIR = REPO_ROOT / "frontend" / "data"
OUT_DIR.mkdir(parents=True, exist_ok=True)

import csv
import unicodedata
import re

def slugify(text):
    text = str(text).strip().lower()
    text = unicodedata.normalize("NFKD", text)
    text = re.sub(r"[^\w\s-]", "", text, flags=re.ASCII)
    text = re.sub(r"[\s_]+", "-", text)
    text = re.sub(r"-+", "-", text)
    return text[:80].strip("-")

# Load categories from data/schemes.csv
CSV_PATH = REPO_ROOT / "data" / "schemes.csv"
slug_to_category = {}
name_to_category = {}
name_slug_to_category = {}

if CSV_PATH.exists():
    with open(CSV_PATH, encoding="utf-8", errors="ignore") as f:
        reader = csv.DictReader(f)
        for row in reader:
            cat = row.get("category", "")
            slug_to_category[row["slug"]] = cat
            name_to_category[row["name"].strip().lower()] = cat
            name_slug_to_category[slugify(row["name"])] = cat
    print(f"Loaded category mappings for {len(slug_to_category)} schemes from schemes.csv")

def get_category_for_rule(rule):
    rid = rule.get("id", "")
    rname = rule.get("name", "").strip().lower()
    return (
        name_slug_to_category.get(rid)
        or slug_to_category.get(rid)
        or name_to_category.get(rname)
        or ""
    )

# 1. Load Tier-1 Rules
tier1_files = sorted(TIER1_DIR.glob("*.json"))
tier1_rules = [json.loads(f.read_text(encoding="utf-8")) for f in tier1_files]
for r in tier1_rules:
    r["category"] = get_category_for_rule(r)
print(f"Loaded {len(tier1_rules)} tier-1 rules")

# 2. Load Tier-2 Rules and normalise schema to match tier-1
TIER2_DIR = REPO_ROOT / "data" / "rules" / "tier2"
tier2_rules = []
if TIER2_DIR.is_dir():
    for f in sorted(TIER2_DIR.glob("*.json")):
        rule = json.loads(f.read_text(encoding="utf-8"))
        # Normalise: tier-2 uses apply_url / source_url at top level,
        # but the frontend expects  links.info / links.apply
        if "links" not in rule:
            rule["links"] = {}
            if rule.get("source_url"):
                rule["links"]["info"] = rule["source_url"]
            if rule.get("apply_url"):
                rule["links"]["apply"] = rule["apply_url"]
        # Strip private/debug fields the frontend doesn't need
        rule.pop("_eligibility_text", None)
        rule.pop("_criteria_filled", None)
        rule.pop("last_verified", None)
        rule.pop("apply_url", None)
        rule.pop("source_url", None)
        rule["category"] = get_category_for_rule(rule)
        tier2_rules.append(rule)
    print(f"Loaded {len(tier2_rules)} tier-2 rules")
else:
    print("No tier-2 rules directory found, skipping")

# 3. Combine all rules — tier-1 first, then tier-2
all_rules = tier1_rules + tier2_rules
rules_js = f"// Auto-generated by scripts/prepare_frontend_data.py\nwindow.ALL_RULES = {json.dumps(all_rules, indent=2, ensure_ascii=False)};\n"
(OUT_DIR / "rules.js").write_text(rules_js, encoding="utf-8")
print(f"Generated frontend/data/rules.js ({len(all_rules)} total rules: {len(tier1_rules)} tier-1 + {len(tier2_rules)} tier-2)")

# 2. Field Catalog
catalog_data = json.loads(CATALOG_FILE.read_text(encoding="utf-8"))
fields_js = f"// Auto-generated by scripts/prepare_frontend_data.py\nwindow.FIELD_CATALOG = {json.dumps(catalog_data, indent=2, ensure_ascii=False)};\n"
(OUT_DIR / "fields.js").write_text(fields_js, encoding="utf-8")
print(f"Generated frontend/data/fields.js ({len(catalog_data.get('fields', []))} fields)")

